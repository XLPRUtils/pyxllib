from xlsln.kq5034.courses.d260301禅宗46期五阶 import 考勤课程


def test_打卡应返款分别封顶16次():
    assert 考勤课程._计算打卡应返款(16, 16) == 160
    assert 考勤课程._计算打卡应返款(20, 20) == 160
    assert 考勤课程._计算打卡应返款(99, 97) == 160


def test_打卡应返款未满时按实际次数计算():
    assert 考勤课程._计算打卡应返款(10, 12) == 110
    assert 考勤课程._计算打卡应返款('', None) == 0
